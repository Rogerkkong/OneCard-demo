/** What a card's chip would hold: its digest in the school, its counter and its balance. */
function chip(school, uid, balanceSen = 0) {
  return { digest: t.schools.cardDigestFor(school.id, uid), last4: uid.slice(-4), cardSeq: 0, balanceSen };
}

let orders = 0;
/** Money onto a member's mirror the way the kiosk flow books it: paid, then added to the card. */
function fund(school, memberId, amountSen) {
  const orderId = `ord_test${++orders}`;
  t.ledger.post({
    schoolId: school.id,
    idemKey: `TOPUP:${orderId}:PAID`,
    kind: 'TOPUP',
    lines: [{ kind: 'CASH_RECEIVED', side: 'DR', amountSen }, { kind: 'WAITING_TO_BE_ADDED', memberId, side: 'CR', amountSen }],
  });
  t.ledger.post({
    schoolId: school.id,
    idemKey: `TOPUP:${orderId}:ADDED`,
    kind: 'TOPUP',
    lines: [{ kind: 'WAITING_TO_BE_ADDED', memberId, side: 'DR', amountSen }, { kind: 'STUDENT_WALLET', memberId, side: 'CR', amountSen }],
  });
}

/** A member's card holding `balanceSen`, with the same amount on the platform's mirror. */
function funded(school, key, balanceSen) {
  const member = school.members[key];
  fund(school, member.id, balanceSen);
  return chip(school, member.uid, balanceSen);
}

/** The chip's part of a debit, as VirtualCard.debit fills it in: next counter, balance before and after. */
function debit(card, fields, amountSen) {
  card.cardSeq += 1;
  const balanceBeforeSen = card.balanceSen;
  card.balanceSen -= amountSen;
  return {
    priceVersion: 1,
    listVersion: 1,
    at: t.ctx.clock.iso(),
    ...fields,
    card: card.digest,
    last4: card.last4,
    cardSeq: card.cardSeq,
    amountSen,
    balanceBeforeSen,
    balanceAfterSen: card.balanceSen,
  };
}

/** A completed canteen record. items: [code, qty, priceSen = the default list's price]. */
function sale(card, { origin = 'CANTEEN-01', n, items = [['NASI-LEMAK', 1]], amountSen, ...rest } = {}) {
  const lines = items.map(([itemCode, qty, priceSen = PRICE[itemCode]]) => ({ code: itemCode, qty, priceSen }));
  const itemsSen = lines.reduce((sum, l) => sum + l.qty * l.priceSen, 0);
  return debit(card, { txn: deviceTxnNo(origin, n), origin, kind: 'SALE', items: lines, ...rest }, amountSen ?? itemsSen);
}

/** A completed water record; the amount follows waterChargeSen unless given. */
function water(card, { origin = 'WATER-01', n, ml, perLitreSen = PER_LITRE, minChargeSen = MIN_CHARGE, amountSen, ...rest } = {}) {
  const charge = amountSen ?? waterChargeSen(ml, perLitreSen, minChargeSen);
  return debit(card, { txn: deviceTxnNo(origin, n), origin, kind: 'WATER', ml, perLitreSen, ...rest }, charge);
}

/** settlement.receive into school A (or `school`), delivered by the record's own machine unless told otherwise. */
function receive(record, { school = t.a, via = 'MQTT', uploader = via === 'KIOSK_READBACK' ? 'KIOSK-01' : record?.origin } = {}) {
  const device = uploader == null ? undefined : school.devices[uploader];
  return t.settlement.receive({ schoolId: school.id, uploaderDeviceId: device ? device.id : null, via, record });
}

/** The books balance, and sales payable holds exactly the posted purchases. */
function assertBooks(school = t.a) {
  const tb = t.ledger.trialBalance(school.id);
  assert.equal(tb.balanced, true, `the books of ${school.code} do not balance`);
  const posted = t.ctx.db.get("SELECT coalesce(sum(amount_sen), 0) AS s FROM purchase WHERE school_id = ? AND status = 'POSTED'", school.id).s;
  assert.equal(t.ledger.balance(school.id, 'SALES_PAYABLE'), posted);
  return tb;
}


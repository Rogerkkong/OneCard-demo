describe('receive: purchases that check out', () => {
  test('a canteen sale over MQTT is POSTED: purchase row, posting and mirror', () => {
    const card = funded(t.a, 'aina', 2000);
    const record = sale(card, { n: 1, items: [['NASI-LEMAK', 1], ['TEH-TARIK', 1]] });
    const res = receive(record);
    assert.deepEqual(Object.keys(res).sort(), ['differences', 'purchaseId', 'status']);
    assert.equal(res.status, 'POSTED');
    assert.match(res.purchaseId, /^pur_/);
    assert.deepEqual(res.differences, []);

    const row = purchaseRow(res.purchaseId);
    const posting = t.ledger.findByIdemKey(t.a.id, 'PURCHASE:CANTEEN-01:CANTEEN-01-000001');
    assert.deepEqual({ ...row }, {
      id: res.purchaseId,
      school_id: t.a.id,
      origin_device_code: 'CANTEEN-01',
      device_txn: 'CANTEEN-01-000001',
      txn_number: 1,
      uploader_device_id: t.a.devices['CANTEEN-01'].id,
      via: 'MQTT',
      kind: 'SALE',
      card_digest: card.digest,
      card_id: t.a.members.aina.cardId,
      member_id: t.a.members.aina.id,
      amount_sen: 530,
      ml: null,
      price_version: 1,
      list_version: 1,
      card_seq: 1,
      balance_before_sen: 2000,
      balance_after_sen: 1470,
      occurred_at: T0,
      received_at: T0,
      status: 'POSTED',
      posting_id: posting.id,
      late: 0,
      raw: canonicalJson(record),
    });
    // DR the member's wallet / CR sales payable, linked to the purchase
    assert.equal(posting.kind, 'PURCHASE');
    assert.equal(posting.ref, res.purchaseId);
    assert.equal(posting.memo, 'Sale CANTEEN-01-000001');
    assert.deepEqual(posting.lines, [
      { kind: 'STUDENT_WALLET', memberId: t.a.members.aina.id, side: 'DR', amountSen: 530 },
      { kind: 'SALES_PAYABLE', memberId: null, side: 'CR', amountSen: 530 },
    ]);
    // the mirror follows the card
    assert.equal(wallet(t.a, 'aina'), card.balanceSen);
    assert.equal(wallet(t.a, 'aina'), 1470);
    assert.equal(t.differences.list(t.a.id).length, 0);
    assertBooks();
  });

  test('water is charged by the litre, with the minimum charge for a small pour', () => {
    const card = funded(t.a, 'aina', 2000);
    const big = receive(water(card, { n: 1, ml: 650 })); // 650 ml at 20 sen a litre = 13 sen
    const small = receive(water(card, { n: 2, ml: 10 })); // below the 5 sen minimum charge
    for (const res of [big, small]) {
      assert.equal(res.status, 'POSTED');
      assert.deepEqual(res.differences, []);
    }
    assert.equal(waterChargeSen(650, PER_LITRE, MIN_CHARGE), 13);
    const [b, s] = [purchaseRow(big.purchaseId), purchaseRow(small.purchaseId)];
    assert.deepEqual([b.kind, b.ml, b.amount_sen, s.ml, s.amount_sen], ['WATER', 650, 13, 10, 5]);
    assert.equal(t.ledger.findByIdemKey(t.a.id, 'PURCHASE:WATER-01:WATER-01-000001').memo, 'Water 650 ml WATER-01-000001');
    assert.equal(wallet(t.a, 'aina'), 2000 - 13 - 5);
    assertBooks();
  });

  test('a zero-amount record is stored POSTED but moves no money', () => {
    // a price list with no minimum charge: a few millilitres cost nothing
    const v2 = t.configs.publish({
      schoolId: t.a.id, kind: 'prices', content: { ...DEFAULT_PRICES, water: { perLitreSen: 20, minChargeSen: 0 } }, actor: 'test',
    });
    const card = funded(t.a, 'aina', 1000);
    const record = water(card, { n: 1, ml: 20, minChargeSen: 0, priceVersion: v2.version });
    assert.equal(record.amountSen, 0);
    const res = receive(record);
    assert.deepEqual(res, { status: 'POSTED', purchaseId: res.purchaseId, differences: [] });
    const row = purchaseRow(res.purchaseId);
    assert.deepEqual([row.status, row.amount_sen, row.posting_id, row.member_id], ['POSTED', 0, null, t.a.members.aina.id]);
    assert.equal(t.ledger.findByIdemKey(t.a.id, 'PURCHASE:WATER-01:WATER-01-000001'), null);
    assert.equal(purchasePostings().length, 0);
    assert.equal(wallet(t.a, 'aina'), 1000);
    // stored like any other: a second copy is a duplicate
    assert.equal(receive(record, { via: 'JOURNAL_BATCH' }).status, 'DUPLICATE');
    assertBooks();
  });
});

describe('receive: prices', () => {
  test("a sale is checked against the price list version the machine used, not today's", () => {
    const content = { ...DEFAULT_PRICES, items: DEFAULT_PRICES.items.map((i) => (i.code === 'NASI-LEMAK' ? { ...i, priceSen: 380 } : i)) };
    assert.equal(t.configs.publish({ schoolId: t.a.id, kind: 'prices', content, actor: 'test' }).version, 2);
    const card = funded(t.a, 'aina', 5000);
    // an offline machine still on version 1 charges the old price: fine
    assert.deepEqual(receive(sale(card, { origin: 'CANTEEN-02', n: 1 })).differences, []);
    // a machine on version 2 charges the new price: fine
    assert.deepEqual(receive(sale(card, { n: 1, items: [['NASI-LEMAK', 1, 380]], priceVersion: 2 })).differences, []);
    // a machine saying version 2 but charging the old price: flagged, and posted for what the card paid
    const res = receive(sale(card, { n: 2, items: [['NASI-LEMAK', 2, 350]], priceVersion: 2 }));
    assert.equal(res.status, 'POSTED');
    assert.deepEqual(res.differences, ['PRICE_MISMATCH']);
    const [d] = diffsOf('PRICE_MISMATCH');
    assert.equal(d.ref, 'CANTEEN-01:CANTEEN-01-000002');
    assert.deepEqual(d.detail, {
      origin: 'CANTEEN-01',
      txn: 'CANTEEN-01-000002',
      kind: 'SALE',
      priceVersion: 2,
      amountSen: 700,
      expectedSen: 760,
      problems: ['NASI-LEMAK charged at 350 sen, the list says 380 sen'],
    });
    assert.equal(t.ledger.findByIdemKey(t.a.id, 'PURCHASE:CANTEEN-01:CANTEEN-01-000002').lines[0].amountSen, 700);
    assert.equal(wallet(t.a, 'aina'), 5000 - 350 - 380 - 700);
    assertBooks();
  });

  test('items that do not add up to the amount are a PRICE_MISMATCH', () => {
    const card = funded(t.a, 'aina', 2000);
    // 350 + 2 x 180 = 710, but the record charged 700
    const res = receive(sale(card, { n: 1, items: [['NASI-LEMAK', 1], ['TEH-TARIK', 2]], amountSen: 700 }));
    assert.deepEqual([res.status, res.differences], ['POSTED', ['PRICE_MISMATCH']]);
    const [d] = diffsOf('PRICE_MISMATCH');
    assert.equal(d.detail.expectedSen, 710);
    assert.deepEqual(d.detail.problems, ['the items add up to 710 sen, the record charged 700 sen']);
    assert.equal(wallet(t.a, 'aina'), 1300);
    assertBooks();
  });

  test('an item that is not on the price list version is a PRICE_MISMATCH', () => {
    const card = funded(t.a, 'aina', 2000);
    const res = receive(sale(card, { n: 1, items: [['KUIH-LAPIS', 1, 120], ['BUAH', 1]] }));
    assert.deepEqual([res.status, res.differences], ['POSTED', ['PRICE_MISMATCH']]);
    const [d] = diffsOf('PRICE_MISMATCH');
    assert.equal(d.detail.expectedSen, null); // the list cannot say what the purchase should cost
    assert.deepEqual(d.detail.problems, ['KUIH-LAPIS is not on price list version 1']);
    assert.equal(wallet(t.a, 'aina'), 2000 - 220);
    assertBooks();
  });

  test("water: the litre price must be the version's and the amount must be waterChargeSen", () => {
    const card = funded(t.a, 'aina', 5000);
    // a machine with another litre price
    const other = receive(water(card, { n: 1, ml: 650, perLitreSen: 25 }));
    assert.deepEqual([other.status, other.differences], ['POSTED', ['PRICE_MISMATCH']]);
    // the right litre price, but the minimum charge left out
    const free = receive(water(card, { n: 2, ml: 10, minChargeSen: 0 }));
    assert.deepEqual([free.status, free.differences], ['POSTED', ['PRICE_MISMATCH']]);
    const byRef = Object.fromEntries(diffsOf('PRICE_MISMATCH').map((d) => [d.ref, d.detail]));
    assert.deepEqual(byRef['WATER-01:WATER-01-000001'], {
      origin: 'WATER-01',
      txn: 'WATER-01-000001',
      kind: 'WATER',
      priceVersion: 1,
      amountSen: 16,
      expectedSen: 13,
      problems: ['water charged at 25 sen a litre, the list says 20 sen', '650 ml costs 13 sen, the record charged 16 sen'],
    });
    assert.deepEqual(byRef['WATER-01:WATER-01-000002'].problems, ['10 ml costs 5 sen, the record charged 0 sen']);
    assert.equal(byRef['WATER-01:WATER-01-000002'].expectedSen, 5);
    assert.equal(wallet(t.a, 'aina'), 5000 - 16);
    assertBooks();
  });

  test('a price list version that was never issued is PRICE_VERSION_UNKNOWN, and still posted', () => {
    const card = funded(t.a, 'aina', 2000);
    const res = receive(sale(card, { n: 1, priceVersion: 7 }));
    assert.deepEqual([res.status, res.differences], ['POSTED', ['PRICE_VERSION_UNKNOWN']]);
    const [d] = diffsOf('PRICE_VERSION_UNKNOWN');
    assert.equal(d.ref, 'CANTEEN-01:CANTEEN-01-000001');
    assert.deepEqual(d.detail, { origin: 'CANTEEN-01', txn: 'CANTEEN-01-000001', priceVersion: 7, latestVersion: 1 });
    assert.equal(wallet(t.a, 'aina'), 1650);
    // a version of another school does not count either
    t.configs.publish({ schoolId: t.b.id, kind: 'prices', content: DEFAULT_PRICES, actor: 'test' }); // smk-beta version 2
    assert.deepEqual(receive(sale(card, { n: 2, priceVersion: 2 })).differences, ['PRICE_VERSION_UNKNOWN']);
    assertBooks();
  });
});

describe('receive: the same record twice', () => {
  test('the same record again is a DUPLICATE however it arrives, and counts once', () => {
    const card = funded(t.a, 'aina', 2000);
    const record = sale(card, { n: 1 });
    const first = receive(record);
    for (const via of PURCHASE_VIAS) {
      assert.deepEqual(receive(structuredClone(record), { via }), { status: 'DUPLICATE', purchaseId: first.purchaseId, differences: [] });
    }
    // canonical JSON: the same fields in another order are the same record
    const reordered = Object.fromEntries(Object.entries(record).reverse());
    assert.deepEqual(receive(reordered), { status: 'DUPLICATE', purchaseId: first.purchaseId, differences: [] });
    assert.equal(countRows('purchase'), 1);
    assert.equal(purchaseRow(first.purchaseId).via, 'MQTT'); // the first copy is the one kept
    assert.equal(purchasePostings().length, 1);
    assert.equal(wallet(t.a, 'aina'), 1650);
    assert.equal(t.differences.list(t.a.id).length, 0);
    assertBooks();
  });

  test('the same txn with other content is a DUPLICATE CONFLICT: nothing is posted again', () => {
    const card = funded(t.a, 'aina', 2000);
    const record = sale(card, { n: 1 });
    const first = receive(record);
    const other = { ...record, items: [{ code: 'MEE-GORENG', qty: 1, priceSen: 400 }], amountSen: 400, balanceAfterSen: 1600 };
    const res = receive(other, { via: 'KIOSK_READBACK' });
    assert.deepEqual(res, { status: 'DUPLICATE', purchaseId: first.purchaseId, code: 'CONFLICT', differences: ['DUPLICATE_CONFLICT'] });
    const [d] = diffsOf('DUPLICATE_CONFLICT');
    assert.equal(d.ref, 'CANTEEN-01:CANTEEN-01-000001');
    assert.deepEqual(d.detail, { purchaseId: first.purchaseId, changed: ['amountSen', 'balanceAfterSen', 'items'], stored: record, received: other });
    // the first copy is kept as it was
    assert.equal(purchaseRow(first.purchaseId).raw, canonicalJson(record));
    assert.equal(purchaseRow(first.purchaseId).amount_sen, 350);
    assert.equal(purchasePostings().length, 1);
    assert.equal(wallet(t.a, 'aina'), 1650);
    // yet another version: still a conflict, still one difference to look at
    assert.equal(receive({ ...record, listVersion: 4 }).code, 'CONFLICT');
    assert.equal(diffsOf('DUPLICATE_CONFLICT').length, 1);
    assert.equal(countRows('purchase'), 1);
    assertBooks();
  });

  test('the same txn number written with more leading zeros is the same transaction', () => {
    const card = funded(t.a, 'aina', 2000);
    const record = sale(card, { n: 17 });
    const first = receive(record);
    const res = receive({ ...record, txn: 'CANTEEN-01-0000017' });
    assert.deepEqual(res, { status: 'DUPLICATE', purchaseId: first.purchaseId, code: 'CONFLICT', differences: ['DUPLICATE_CONFLICT'] });
    const [d] = diffsOf('DUPLICATE_CONFLICT');
    assert.equal(d.ref, 'CANTEEN-01:CANTEEN-01-000017');
    assert.deepEqual(d.detail.changed, ['txn']);
    assert.equal(countRows('purchase'), 1);
    assert.equal(wallet(t.a, 'aina'), 1650);
    assertBooks();
  });
});


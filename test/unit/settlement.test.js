/** A school with machines, members holding cards, the default prices and block list version 1. */
function addSchool(svc, schoolCode, name, people, machines) {
  const school = svc.schools.createSchool({ code: schoolCode, name });
  const devices = {};
  for (const [deviceCode, type] of machines) {
    devices[deviceCode] = svc.devices.registerDevice({ schoolId: school.id, code: deviceCode, type, actor: 'test' }).device;
  }
  const members = {};
  for (const [key, p] of Object.entries(people)) {
    const member = svc.schools.addMember({ schoolId: school.id, memberNo: p.no, name: p.name });
    const card = svc.schools.issueCard({ schoolId: school.id, memberId: member.id, uid: p.uid, actor: 'test' });
    members[key] = { id: member.id, name: p.name, uid: p.uid, cardId: card.id };
  }
  svc.configs.publish({ schoolId: school.id, kind: 'prices', content: DEFAULT_PRICES, actor: 'test' });
  svc.configs.ensureBlockList({ schoolId: school.id, actor: 'test' });
  return { id: school.id, code: schoolCode, devices, members };
}


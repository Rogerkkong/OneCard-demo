function addSchool(svc, code, name, people, machines) {
  const school = svc.schools.createSchool({ code, name });
  const m = {};
  for (const [deviceCode, type] of machines) {
    const { device, secret } = svc.devices.registerDevice({ schoolId: school.id, code: deviceCode, type, actor: 'test' });
    m[deviceCode] = { id: device.id, code: deviceCode, type, secret, school: { id: school.id, code }, seq: 0 };
  }
  const members = {};
  for (const [key, p] of Object.entries(people)) {
    const member = svc.schools.addMember({ schoolId: school.id, memberNo: p.no, name: p.name });
    const card = svc.schools.issueCard({ schoolId: school.id, memberId: member.id, uid: p.uid, actor: 'test' });
    members[key] = { id: member.id, uid: p.uid, cardId: card.id, digest: card.digest };
  }
  svc.configs.publish({ schoolId: school.id, kind: 'prices', content: DEFAULT_PRICES, actor: 'test' });
  svc.configs.publish({ schoolId: school.id, kind: 'settings', content: DEFAULT_SETTINGS, actor: 'test' });
  svc.configs.ensureBlockList({ schoolId: school.id, actor: 'test' });
  return { id: school.id, code, m, members };
}


let kioskTxns = 0;
/** Money onto a member's card through the real flow: a school subsidy, then the kiosk adds it. */
function fund(school, key, amountSen) {
  const member = school.members[key];
  const order = t.topups.grantSubsidy({ schoolId: school.id, memberId: member.id, amountSen, actor: 'test', note: 'start' });
  t.topups.kioskConfirm({
    schoolId: school.id,
    kioskDeviceId: school.m['KIOSK-01'].id,
    kioskDeviceCode: 'KIOSK-01',
    orderId: order.id,
    result: 'ADDED',
    amountSen,
    cardDigest: member.digest,
    balanceAfterOnCardSen: amountSen,
    kioskTxn: deviceTxnNo('KIOSK-01', ++kioskTxns),
  });
  // the chip: the kiosk's credit raised its counter too
  return { digest: member.digest, last4: member.uid.slice(-4), cardSeq: 1, balanceSen: amountSen };
}

function debit(card, fields, amountSen) {
  card.cardSeq += 1;
  const balanceBeforeSen = card.balanceSen;
  card.balanceSen -= amountSen;
  return {
    priceVersion: 1,
    listVersion: 1,
    at: t.ctx.clock.iso(),
    currency: 'MYR',
    ...fields,
    card: card.digest,
    last4: card.last4,
    cardSeq: card.cardSeq,
    amountSen,
    balanceBeforeSen,
    balanceAfterSen: card.balanceSen,
  };
}

function sale(card, { origin = 'CANTEEN-01', n, items = [['NASI-LEMAK', 1]] } = {}) {
  const lines = items.map(([code, qty]) => ({ code, qty, priceSen: PRICE[code] }));
  return debit(card, { txn: deviceTxnNo(origin, n), origin, kind: 'SALE', items: lines }, lines.reduce((s, l) => s + l.qty * l.priceSen, 0));
}

function water(card, { origin = 'WATER-01', n, ml }) {
  return debit(card, { txn: deviceTxnNo(origin, n), origin, kind: 'WATER', ml, perLitreSen: PER_LITRE }, waterChargeSen(ml, PER_LITRE, MIN_CHARGE));
}


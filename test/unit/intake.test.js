/** A signed envelope from machine `m`; its seq counts up unless given. */
function envelope(m, type, body, { seq, txn, at, id, school, device, v } = {}) {
  const env = buildEnvelope({ school: school ?? m.school.code, device: device ?? m.code, seq: seq ?? ++m.seq, at: at ?? t.ctx.clock.iso(), type, txn, body });
  if (id !== undefined) env.id = id;
  if (v !== undefined) env.v = v;
  return signEnvelope(m.secret, env);
}

const topicOf = (m, channel) => topicFor(m.school.code, m.code, channel);
/** Deliver an envelope on machine m's own topic for its type (or `channel`). */
const deliver = (m, env, channel = UP_TYPES[env.type] ?? 'records') => t.intake.handle(topicOf(m, channel), JSON.stringify(env));
const send = (m, type, body, opts = {}) => deliver(m, envelope(m, type, body, opts), opts.channel);

const heartbeatBody = (versions = { prices: 1, settings: 1, blocklist: 1 }) => ({ fw: '1.0.0-lab', health: 'OK', listVersions: versions, journalUnsent: 0 });


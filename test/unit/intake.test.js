const wallet = (school, key) => t.ledger.balance(school.id, 'STUDENT_WALLET', school.members[key].id);
const purchases = (school) => t.settlement.listPurchases(school.id);
const lastSeq = (m) => t.devices.getDevice(m.school.id, m.id).lastSeq;
const inbound = (school) => t.ctx.db.get('SELECT count(*) AS n FROM inbound_message WHERE school_id = ?', school.id).n;
const logOf = (m) => t.devices.listLog(m.school.id, { deviceId: m.id });
const refusedEvents = () => eventsOf(t.ctx, 'intake.refused');

function assertBooks(school) {
  const tb = t.ledger.trialBalance(school.id);
  assert.equal(tb.balanced, true, `the books of ${school.code} do not balance`);
  const posted = t.ctx.db.get("SELECT coalesce(sum(amount_sen), 0) AS s FROM purchase WHERE school_id = ? AND status = 'POSTED'", school.id).s;
  assert.equal(t.ledger.balance(school.id, 'SALES_PAYABLE'), posted);
}

/** A refusal: the answer, nothing recorded, the seq untouched, a WARN line in the machine's log and an event. */
function assertRefused(res, code, m, { before } = {}) {
  assert.equal(res.result, 'REFUSED', JSON.stringify(res));
  assert.equal(res.code, code, JSON.stringify(res));
  assert.equal(typeof res.detail.message, 'string');
  if (m) {
    const [entry] = logOf(m);
    assert.equal(entry.code, code);
    assert.equal(entry.level, 'WARN');
    assert.equal(entry.deviceCode, m.code);
    if (before) {
      assert.equal(lastSeq(m), before.seq, 'a refused message must not use up its seq');
      assert.equal(inbound(m.school), before.inbound, 'a refused message must not be recorded');
    }
  }
  const event = refusedEvents().at(-1);
  assert.equal(event.data.code, code);
}

